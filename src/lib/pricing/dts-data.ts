/**
 * یکسان‌سازی نام شهر برای مقایسه — همان الگوی normalize در
 * chapar/city-map.ts و tapin/city-map.ts (حذف نیم‌فاصله/NBSP/zero-width
 * space، یکسان‌سازی ی/ك عربی-فارسی، و حذف پیشوندهای رایج استان/شهرستان/شهر).
 */
export function normalizeDtsCityName(name: string): string {
  return name
    .replace(/[‌​ ]/g, " ")
    .trim()
    .replace(/[یي]/g, "ی")
    .replace(/[کك]/g, "ک")
    .replace(/\s+/g, " ")
    .replace(/^(استان|شهرستان|شهر)\s+/, "")
    .trim();
}

const DTS_CITY_TO_ZONE = new Map<string, 1 | 2 | 3 | 4 | 5>();
for (const [zone, cities] of Object.entries(DTS_ZONE_CITIES)) {
  for (const city of cities) {
    DTS_CITY_TO_ZONE.set(normalizeDtsCityName(city), Number(zone) as 1 | 2 | 3 | 4 | 5);
  }
}

/** زون یک شهر بادرو را برمی‌گرداند؛ اگر DTS آن شهر را پوشش نمی‌دهد، null. */
export function findDtsZoneForCity(cityName: string): 1 | 2 | 3 | 4 | 5 | null {
  return DTS_CITY_TO_ZONE.get(normalizeDtsCityName(cityName)) ?? null;
}
