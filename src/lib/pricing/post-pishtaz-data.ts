/**
 * یکسان‌سازی نام شهر برای مقایسه — همان الگوی normalize در
 * chapar/city-map.ts، tapin/city-map.ts، و dts-data.ts (کپی‌شده مستقل، نه
 * import شده، طبق دستور معماری این فایل).
 */
export function normalizePostPishtazCityName(name: string): string {
  return name
    .replace(/[‌​ ]/g, " ")
    .trim()
    .replace(/[یي]/g, "ی")
    .replace(/[کك]/g, "ک")
    .replace(/\s+/g, " ")
    .replace(/^(استان|شهرستان|شهر)\s+/, "")
    .trim();
}

const POST_PISHTAZ_CITY_TO_ZONE = new Map<string, 1 | 2 | 3 | 4 | 5>();
for (const [zone, cities] of Object.entries(POST_PISHTAZ_ZONE_CITIES)) {
  for (const city of cities) {
    POST_PISHTAZ_CITY_TO_ZONE.set(
      normalizePostPishtazCityName(city),
      Number(zone) as 1 | 2 | 3 | 4 | 5
    );
  }
}

/** زون یک شهر بادرو را برمی‌گرداند؛ اگر پست پیشتاز آن شهر را پوشش نمی‌دهد، null. */
export function findPostPishtazZoneForCity(cityName: string): 1 | 2 | 3 | 4 | 5 | null {
  return POST_PISHTAZ_CITY_TO_ZONE.get(normalizePostPishtazCityName(cityName)) ?? null;
}
